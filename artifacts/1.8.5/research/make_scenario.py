#!/usr/bin/env python
"""Write a QaProbe1201 script for the Zero SMP performance runs.

usage: make_scenario.py <out.txt> [--quick] [--no-move] [--phases A,A2,B,C,D,E]

Phases (each logs `PERF phase=<name> begin/end` so jfr_attrib/analyze_run can cut the recording by time):
  S  settle      stand at (0,surface,0), clear, let chunks + LODs build
  A  idle        creative, HUD on
  A2 idle-nohud  F1 (hideGui) - difference to A = whole GUI
  B  fly         spectator, forward+sprint, circle (new chunks all the time: worldgen + meshing + LOD building)
  C  rain        creative idle in rain
  D  mobs        60 cows around the player, rain off
  E  thunder     thunder + rain
Z at the end: spark health/tps/gc into the log (needs spark in the sandbox mods), final dump state, quit.
"""
import argparse

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('out'); ap.add_argument('--quick', action='store_true'); ap.add_argument('--no-move', action='store_true')
    ap.add_argument('--phases', default='A,A2,B,C,D,E'); ap.add_argument('--k', type=float, default=None)
    a = ap.parse_args()
    k = a.k if a.k is not None else (0.25 if a.quick else 1.0)
    L = []
    def ph(name, secs, body=None, dump_every=4):
        L.append(f'log PERF phase={name} begin')
        if body: L.extend(body)
        n = max(1, int(secs * k / dump_every))
        for _ in range(n):
            L.append(f'wait {dump_every}s'); L.append('dump state')
        L.append(f'log PERF phase={name} end')
    want = a.phases.split(',')
    L += ['# generated by make_scenario.py', 'log PERF scenario begin', 'cmd gamemode creative', 'cmd time set day', 'cmd weather clear',
          'cmd spreadplayers 0 0 0 1 false @s', 'look 0 8', 'wait 2s', 'dump state']
    ph('S', 40)
    if 'A' in want: ph('A', 40)
    if 'A2' in want:
        ph('A2', 24, body=['key F1'])
        L.append('key F1'); L.append('wait 1s')
    if 'B' in want and not a.no_move:
        body = ['cmd gamemode spectator', 'cmd tp @s ~ ~12 ~', 'hold forward on', 'hold sprint on']
        L.append('log PERF phase=B begin')
        L += body
        n = max(1, int(64 * k / 4))
        for i in range(n):
            L.append('wait 4s'); L.append(f'look {(i * 14) % 360} 10'); L.append('dump state')
        L += ['hold forward off', 'hold sprint off', 'cmd gamemode creative', 'cmd spreadplayers 0 0 0 1 false @s', 'wait 10s', 'log PERF phase=B end']
    if 'C' in want: ph('C', 40, body=['cmd weather rain'])
    if 'D' in want:
        body = ['cmd weather clear', 'cmd gamerule doMobSpawning false']
        for _ in range(60): body.append('cmd execute at @s run summon minecraft:cow ~ ~ ~')
        ph('D', 40, body=body)
        L.append('cmd kill @e[type=minecraft:cow]')
    if 'E' in want: ph('E', 28, body=['cmd weather thunder'])
    L += ['log PERF phase=Z begin', 'cmd weather clear', 'wait 2s', 'cmd spark health', 'wait 2s', 'cmd spark tps', 'wait 2s', 'cmd spark gc', 'wait 2s',
          'dump state', 'log PERF phase=Z end', 'log PERF scenario end']
    open(a.out, 'w', encoding='utf8', newline='\n').write('\n'.join(L) + '\n')
    print(len(L), 'steps ->', a.out)

if __name__ == '__main__':
    main()
