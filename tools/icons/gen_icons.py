#!/usr/bin/env python3
"""
Regenerates every Flaticon icon artefact from tools/icons/icons.json (icon name -> Flaticon UIcons class, e.g. fi-sr-play).

  1. TheLadsCore/common/.../assets/theladscore/textures/gui/lads_icons.png (+ .mcmeta): white-on-alpha atlas of the used glyphs, the
     in-game icons (LadsGraphics.drawIcon tints it);
  2. TheLadsCore/common/.../client/bridge/IconAtlas.java: icon name -> atlas cell;
  3. TheLadsLauncher/Styles/Icons.axaml: one StreamGeometry per icon (300 x 300 box, y down), drawn by the launcher's Glyph control.

Only the glyphs listed in the manifest ship, never the whole font package. Source: the npm package @flaticon/flaticon-uicons 3.3.1
(Flaticon licence: free with credit, see THIRD_PARTY_NOTICES.txt), unpacked anywhere:
    npm pack @flaticon/flaticon-uicons@3.3.1 && tar xf flaticon-flaticon-uicons-3.3.1.tgz     (-> ./package)
    python tools/icons/gen_icons.py --uicons package
Needs fontTools and Pillow. Outputs are deterministic; run it again after adding a name to the manifest.
"""
import argparse, glob, io, json, math, os, re, sys
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

CELL, GUTTER, SUPERSAMPLE, EM = 32, 1, 8, 300
PITCH = CELL + 2 * GUTTER
FAMILY = "solid", "rounded"          # css/solid/rounded.css, the fi-sr- classes

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PNG = "TheLadsCore/common/src/main/resources/assets/theladscore/textures/gui/lads_icons.png"
JAVA = "TheLadsCore/common/src/main/java/com/thelads/core/client/bridge/IconAtlas.java"
AXAML = "TheLadsLauncher/Styles/Icons.axaml"


def number(v):
    s = f"{v:.1f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--uicons", required=True, help="the unpacked @flaticon/flaticon-uicons package directory")
    ap.add_argument("--repo", default=ROOT)
    a = ap.parse_args()

    manifest = json.load(open(os.path.join(a.repo, "tools/icons/icons.json"), encoding="utf-8"))
    icons = {k: v for k, v in manifest["icons"].items()}
    css = open(os.path.join(a.uicons, "css", FAMILY[0], FAMILY[1] + ".css"), encoding="utf-8").read()
    codes = {m[0]: int(m[1], 16) for m in re.findall(r'\.(fi-sr-[a-z0-9-]+):before\{content:"\\([0-9a-f]+)"\}', css)}
    missing = sorted({c for c in icons.values() if c not in codes})
    if missing:
        sys.exit("not in the font: " + ", ".join(missing))
    woff = glob.glob(os.path.join(a.uicons, "css", f"uicons-{FAMILY[0]}-{FAMILY[1]}-*.woff"))[0]
    font = TTFont(woff)
    cmap, glyphs = font.getBestCmap(), font.getGlyphSet()
    ttf = TTFont(woff)                                    # FreeType reads the TrueType flavour
    ttf.flavor = None
    buf = io.BytesIO()
    ttf.save(buf)

    classes = sorted(set(icons.values()))                  # one cell per glyph, however many names use it
    cell_of = {c: i for i, c in enumerate(classes)}
    columns = max(1, 512 // PITCH)
    side = 512
    while math.ceil(len(classes) / columns) * PITCH > side:
        side *= 2
        columns = side // PITCH

    # Atlas: each glyph drawn big by FreeType and box-filtered down, white with the coverage as alpha (white also where
    # transparent, so linear filtering never darkens the edges).
    big = ImageFont.truetype(io.BytesIO(buf.getvalue()), CELL * SUPERSAMPLE, layout_engine=ImageFont.Layout.BASIC)
    atlas = Image.new("RGBA", (side, side), (255, 255, 255, 0))
    for c in classes:
        tile = Image.new("L", (CELL * SUPERSAMPLE,) * 2, 0)
        ImageDraw.Draw(tile).text((0, 0), chr(codes[c]), font=big, fill=255, anchor="la")
        alpha = tile.resize((CELL, CELL), Image.Resampling.BOX)
        if alpha.getbbox() is None:
            sys.exit("empty glyph " + c)
        i = cell_of[c]
        atlas.paste(Image.merge("RGBA", (*(Image.new("L", (CELL, CELL), 255),) * 3, alpha)),
                    (i % columns * PITCH + GUTTER, i // columns * PITCH + GUTTER))
    for path in (PNG, JAVA, AXAML):
        os.makedirs(os.path.dirname(os.path.join(a.repo, path)), exist_ok=True)
    out = os.path.join(a.repo, PNG)
    atlas.save(out, optimize=True)
    open(out + ".mcmeta", "w", newline="\n").write('{"texture": {"blur": true, "clamp": true}}\n')

    # IconAtlas.java
    names = sorted(icons)
    rows = ",\n".join(f'        "{n}", {cell_of[icons[n]]}' for n in names)
    java = f"""package com.thelads.core.client.bridge;

import java.util.HashMap;
import java.util.Map;

/**
 * GENERATED by tools/icons/gen_icons.py from tools/icons/icons.json; do not edit. Where each icon (Flaticon UIcons, solid rounded) sits in
 * the atlas textures/gui/lads_icons.png: white glyphs on alpha, {CELL} px each, {GUTTER} px apart so linear filtering never bleeds a neighbour.
 */
public final class IconAtlas {{
    public static final String NAMESPACE = "theladscore", PATH = "textures/gui/lads_icons.png";
    public static final int CELL = {CELL}, PITCH = {PITCH}, GUTTER = {GUTTER}, COLUMNS = {columns}, SIZE = {side};
    private static final Map<String, Integer> CELLS = new HashMap<>();
    static {{
        Object[] entries = {{
{rows}
        }};
        for (int i = 0; i < entries.length; i += 2) CELLS.put((String) entries[i], (Integer) entries[i + 1]);
    }}
    private IconAtlas() {{}}

    /** The atlas cell of an icon name, or -1 for a name without a glyph. */
    public static int cell(String name) {{
        Integer cell = CELLS.get(name);
        return cell == null ? -1 : cell;
    }}

    /** The left edge, in the atlas, of a cell's glyph. */
    public static int u(int cell) {{ return cell % COLUMNS * PITCH + GUTTER; }}

    /** The top edge of a cell's glyph. */
    public static int v(int cell) {{ return cell / COLUMNS * PITCH + GUTTER; }}

    public static boolean has(String name) {{ return CELLS.containsKey(name); }}
}}
"""
    open(os.path.join(a.repo, JAVA), "w", encoding="utf-8", newline="\n").write(java)

    # Icons.axaml
    flip = (1, 0, 0, -1, 0, EM)
    lines = []
    for n in names:
        pen = SVGPathPen(glyphs, ntos=number)
        glyphs[cmap[codes[icons[n]]]].draw(TransformPen(pen, flip))
        lines.append(f'  <StreamGeometry x:Key="Ico.{n}">F1 {pen.getCommands()}</StreamGeometry>')
    axaml = ('<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n'
             '  <!-- GENERATED by tools/icons/gen_icons.py from tools/icons/icons.json; do not edit. Flaticon UIcons, solid rounded, 300 x 300 box.\n'
             '       Drawn by the Glyph control (Controls/Glyph.cs): <Glyph Kind="play"/>, or Ico.Name="play" on a Button. -->\n'
             + "\n".join(lines) + "\n</ResourceDictionary>\n")
    open(os.path.join(a.repo, AXAML), "w", encoding="utf-8", newline="\n").write(axaml)
    print(f"{len(names)} icons, {len(classes)} glyphs, atlas {side}x{side}, {os.path.getsize(out)} bytes png")


if __name__ == "__main__":
    main()
